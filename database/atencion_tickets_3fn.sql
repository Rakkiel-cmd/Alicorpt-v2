-- Úsalo únicamente si el usuario de la base de datos de la app no tiene permisos de ALTER/CREATE
-- (ejecútalo entonces con un usuario administrador: Supabase -> SQL Editor).
-- Es seguro repetirlo (IF NOT EXISTS). Desde que existe, el sistema acumula historial;
-- lo ocurrido antes no se puede reconstruir.
