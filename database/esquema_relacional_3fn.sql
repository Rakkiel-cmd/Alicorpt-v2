-- =============================================================================
-- ESQUEMA RELACIONAL NORMALIZADO EN TERCERA FORMA NORMAL (3FN)
-- Compatible con Motor Relacional Local (H2 modo Oracle/PostgreSQL) y PostgreSQL
-- Prohibidas las tablas "al aire": Todo vinculado con PRIMARY KEY y FOREIGN KEY
-- =============================================================================

-- 1. TABLAS MAESTRAS REFERENCIALES (NIVEL 1)
CREATE TABLE IF NOT EXISTS ROLES_SEGURIDAD (
    id_rol          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_rol      VARCHAR(30)  NOT NULL UNIQUE,
    nombre_visible  VARCHAR(60)  NOT NULL,
    nivel_acceso    INT          NOT NULL CHECK (nivel_acceso BETWEEN 1 AND 10),
    descripcion     VARCHAR(200)
);

CREATE TABLE IF NOT EXISTS ESTADOS_USUARIO (
    id_estado       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_estado   VARCHAR(20)  NOT NULL UNIQUE,
    permite_login   CHAR(1)      DEFAULT 'S' NOT NULL CHECK (permite_login IN ('S', 'N')),
    descripcion     VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS CATEGORIAS_PRODUCTO (
    id_categoria     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS PRODUCTOS (
    id_producto      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_codigo       VARCHAR(30)    NOT NULL UNIQUE,
    nombre_producto  VARCHAR(120)   NOT NULL UNIQUE,
    marca            VARCHAR(80)    DEFAULT 'Alicorp' NOT NULL,
    presentacion     VARCHAR(80)    DEFAULT 'Unidad' NOT NULL,
    stock_disponible INT            DEFAULT 500 NOT NULL CHECK (stock_disponible >= 0),
    id_categoria     INT            NOT NULL,
    precio_base      DECIMAL(10, 2) NOT NULL CHECK (precio_base > 0),
    costo_unitario   DECIMAL(10, 2) NOT NULL CHECK (costo_unitario > 0),
    factor_mercado   DECIMAL(6, 4)  DEFAULT 0.0000 NOT NULL,
    activo           CHAR(1)        DEFAULT 'S' NOT NULL CHECK (activo IN ('S', 'N')),
    CONSTRAINT fk_prod_categoria FOREIGN KEY (id_categoria)
        REFERENCES CATEGORIAS_PRODUCTO (id_categoria) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS TIENDAS (
    id_tienda        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_tienda    VARCHAR(30)   NOT NULL UNIQUE,
    nombre_tienda    VARCHAR(120)  NOT NULL UNIQUE,
    canal_venta      VARCHAR(50)   NOT NULL,
    distrito_zona    VARCHAR(80)   NOT NULL,
    temperatura_prom DECIMAL(5, 2) DEFAULT 22.00 NOT NULL
);

-- 2. TABLA DE ADMINISTRADORES Y BIOMETRÍA 128-D (NIVEL 2)
CREATE TABLE IF NOT EXISTS ADMINISTRADORES (
    id_admin         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario          VARCHAR(60)   NOT NULL UNIQUE,
    nombre_completo  VARCHAR(150)  NOT NULL,
    email            VARCHAR(150),
    password_hash    VARCHAR(255)  NOT NULL,
    id_rol           INT           NOT NULL,
    id_estado        INT           NOT NULL,
    face_encoding    TEXT,
    l2_norm          DECIMAL(8, 5),
    fecha_registro   TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_admin_rol FOREIGN KEY (id_rol)
        REFERENCES ROLES_SEGURIDAD (id_rol) ON DELETE RESTRICT,
    CONSTRAINT fk_admin_estado FOREIGN KEY (id_estado)
        REFERENCES ESTADOS_USUARIO (id_estado) ON DELETE RESTRICT
);

-- 3. TABLAS DE SEGURIDAD, ACTIVIDAD Y AUDITORÍA (NIVEL 3 - CASCADA Y RESTRICCIÓN)
CREATE TABLE IF NOT EXISTS ACTIVIDAD_USUARIOS (
    id_actividad     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_admin         INT       NOT NULL,
    fecha_sesion     DATE      NOT NULL,
    tiempo_segundos  INT       DEFAULT 0 NOT NULL CHECK (tiempo_segundos BETWEEN 0 AND 86400),
    primer_ingreso   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    ultimo_latido    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_actividad_admin_dia UNIQUE (id_admin, fecha_sesion),
    CONSTRAINT fk_actividad_admin FOREIGN KEY (id_admin)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS AMPLIACION_AUDITORIA (
    id_auditoria        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_admin_ejecutor   INT          NOT NULL,
    id_admin_objetivo   INT          NULL,
    accion              VARCHAR(80)  NOT NULL,
    detalle             VARCHAR(500) NOT NULL,
    fecha_evento        TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_aud_ejecutor FOREIGN KEY (id_admin_ejecutor)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE CASCADE,
    CONSTRAINT fk_aud_objetivo FOREIGN KEY (id_admin_objetivo)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS CONFIGURACION_SEGURIDAD (
    id_config          INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_parametro    VARCHAR(60)  NOT NULL UNIQUE,
    valor_parametro    VARCHAR(120) NOT NULL,
    id_actualizado_por INT          NULL,
    updated_at         TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_cfg_admin FOREIGN KEY (id_actualizado_por)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS SOLICITUDES_CAMBIO_CLAVE (
    id_solicitud      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nueva_clave       VARCHAR(10) NOT NULL,
    id_solicitante    INT         NOT NULL,
    id_aprobador      INT         NULL,
    estado_solicitud  VARCHAR(20) DEFAULT 'pendiente' NOT NULL
                      CHECK (estado_solicitud IN ('pendiente', 'aprobada', 'rechazada')),
    created_at        TIMESTAMP   DEFAULT CURRENT_TIMESTAMP NOT NULL,
    resolved_at       TIMESTAMP   NULL,
    CONSTRAINT chk_doble_superadmin CHECK (id_aprobador IS NULL OR id_solicitante <> id_aprobador),
    CONSTRAINT fk_sol_solicitante FOREIGN KEY (id_solicitante)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE CASCADE,
    CONSTRAINT fk_sol_aprobador FOREIGN KEY (id_aprobador)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE SET NULL
);

-- 4. TABLA DE HECHOS: TRANSACCIONES ALICORP NORMALIZADA SIN TEXTOS REPETIDOS
CREATE TABLE IF NOT EXISTS TRANSACCIONES_ALICORP (
    id_transaccion    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_operacion   DATE           NOT NULL,
    id_producto       INT            NOT NULL,
    id_tienda         INT            NOT NULL,
    precio_unitario   DECIMAL(10, 2) NOT NULL CHECK (precio_unitario > 0),
    stock_actual      INT            NOT NULL CHECK (stock_actual >= 0),
    temperatura_zona  DECIMAL(5, 2)  NOT NULL,
    cantidad_vendida  INT            NOT NULL CHECK (cantidad_vendida >= 0),
    ventas_totales    DECIMAL(12, 2) NOT NULL CHECK (ventas_totales >= 0),
    CONSTRAINT fk_trx_producto FOREIGN KEY (id_producto)
        REFERENCES PRODUCTOS (id_producto) ON DELETE RESTRICT,
    CONSTRAINT fk_trx_tienda FOREIGN KEY (id_tienda)
        REFERENCES TIENDAS (id_tienda) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_trx_prod_tienda ON TRANSACCIONES_ALICORP (id_producto, id_tienda);
CREATE INDEX IF NOT EXISTS idx_trx_fecha ON TRANSACCIONES_ALICORP (fecha_operacion);

-- 5. EMPRESAS COMPETIDORAS Y REPORTES PREDICTIVOS VINCULADOS POR FK A PRODUCTOS
CREATE TABLE IF NOT EXISTS EMPRESAS_COMPETENCIA (
    id_competencia               INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_empresa               VARCHAR(30)    NOT NULL,
    nombre_empresa               VARCHAR(120)   NOT NULL,
    perfil_estrategia            VARCHAR(250)   NOT NULL,
    id_producto_alicorp          INT            NOT NULL,
    marca_competidora            VARCHAR(120)   NOT NULL,
    precio_promedio              DECIMAL(10, 2) NOT NULL,
    costo_unitario               DECIMAL(10, 2) NOT NULL,
    stock_promedio               INT            NOT NULL,
    ventas_historicas_soles      DECIMAL(14, 2) NOT NULL,
    ganancias_netas_historicas   DECIMAL(14, 2) NOT NULL,
    perdida_estimada_competencia DECIMAL(14, 2) NOT NULL,
    cuota_mercado_pct            DECIMAL(5, 2)  NOT NULL,
    CONSTRAINT uq_comp_emp_prod UNIQUE (codigo_empresa, id_producto_alicorp),
    CONSTRAINT fk_comp_producto FOREIGN KEY (id_producto_alicorp)
        REFERENCES PRODUCTOS (id_producto) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS REPORTES_MENSUALES_PREDICHOS (
    id_reporte         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    periodo_mes        VARCHAR(7)     NOT NULL,
    id_producto        INT            NOT NULL,
    precio_estimado    DECIMAL(10, 2) NOT NULL,
    unidades_predichas INT            NOT NULL,
    ventas_predichas   DECIMAL(14, 2) NOT NULL,
    variacion_pct      DECIMAL(6, 2)  NOT NULL,
    estado_rentab      VARCHAR(20)    NOT NULL,
    id_generado_por    INT            NULL,
    fecha_calculo      TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uq_rep_periodo_prod UNIQUE (periodo_mes, id_producto),
    CONSTRAINT fk_rep_producto FOREIGN KEY (id_producto)
        REFERENCES PRODUCTOS (id_producto) ON DELETE CASCADE,
    CONSTRAINT fk_rep_admin FOREIGN KEY (id_generado_por)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE SET NULL
);

-- 6. E-COMMERCE, PEDIDOS E INCIDENCIAS (3FN CON FKs ESTRICTAS)
CREATE TABLE IF NOT EXISTS COMPRAS_TIENDA (
    id_compra         INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_nombre    VARCHAR(150)   NOT NULL,
    cliente_correo    VARCHAR(150)   NOT NULL,
    cliente_telefono  VARCHAR(40)    NOT NULL,
    cliente_direccion VARCHAR(250)   NOT NULL,
    total             DECIMAL(12, 2) NOT NULL CHECK (total >= 0),
    estado            VARCHAR(20)    DEFAULT 'pendiente' NOT NULL
                      CHECK (estado IN ('pendiente', 'preparando', 'enviado', 'entregado', 'cancelado')),
    fecha_compra      TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS COMPRAS_TIENDA_DETALLE (
    id_detalle      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra       INT            NOT NULL,
    id_producto     INT            NOT NULL,
    cantidad        INT            NOT NULL CHECK (cantidad > 0),
    precio_unitario DECIMAL(10, 2) NOT NULL CHECK (precio_unitario > 0),
    subtotal        DECIMAL(12, 2) NOT NULL CHECK (subtotal >= 0),
    CONSTRAINT fk_det_compra FOREIGN KEY (id_compra)
        REFERENCES COMPRAS_TIENDA (id_compra) ON DELETE CASCADE,
    CONSTRAINT fk_det_producto FOREIGN KEY (id_producto)
        REFERENCES PRODUCTOS (id_producto) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS INCIDENCIAS_CONTACTO (
    id_incidencia     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(150) NOT NULL,
    correo            VARCHAR(150) NOT NULL,
    telefono          VARCHAR(40)  DEFAULT '' NOT NULL,
    asunto            VARCHAR(150) NOT NULL,
    mensaje           VARCHAR(1000) NOT NULL,
    estado            VARCHAR(20)  DEFAULT 'pendiente' NOT NULL
                      CHECK (estado IN ('pendiente', 'en_revision', 'resuelto')),
    id_admin_asignado INT          NULL,
    fecha_creacion    TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_inc_admin FOREIGN KEY (id_admin_asignado)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS FALLAS_WEB_SISTEMA (
    id_falla           INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruta               VARCHAR(200) NOT NULL,
    tipo               VARCHAR(80)  NOT NULL,
    mensaje            VARCHAR(500) NOT NULL,
    estado             VARCHAR(20)  DEFAULT 'pendiente' NOT NULL
                       CHECK (estado IN ('pendiente', 'en_revision', 'resuelto')),
    id_admin_resolutor INT          NULL,
    fecha_reporte      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_falla_admin FOREIGN KEY (id_admin_resolutor)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE SET NULL
);
