CREATE TABLE ROLES_SEGURIDAD (
    id_rol          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_rol      VARCHAR2(30)  NOT NULL UNIQUE,
    nombre_visible  VARCHAR2(60)  NOT NULL,
    nivel_acceso    NUMBER(2)     NOT NULL CHECK (nivel_acceso BETWEEN 1 AND 10),
    descripcion     VARCHAR2(200)
);

CREATE TABLE ESTADOS_USUARIO (
    id_estado       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_estado   VARCHAR2(20)  NOT NULL UNIQUE,
    permite_login   CHAR(1)       DEFAULT 'S' NOT NULL CHECK (permite_login IN ('S', 'N')),
    descripcion     VARCHAR2(150)
);

CREATE TABLE CATEGORIAS_PRODUCTO (
    id_categoria     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria VARCHAR2(80) NOT NULL UNIQUE
);

CREATE TABLE PRODUCTOS (
    id_producto      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku_codigo       VARCHAR2(30)  NOT NULL UNIQUE,
    nombre_producto  VARCHAR2(120) NOT NULL UNIQUE,
    id_categoria     NUMBER        NOT NULL,
    precio_base      NUMBER(10, 2) NOT NULL CHECK (precio_base > 0),
    costo_unitario   NUMBER(10, 2) NOT NULL CHECK (costo_unitario > 0),
    factor_mercado   NUMBER(6, 4)  DEFAULT 0.0000 NOT NULL,
    activo           CHAR(1)       DEFAULT 'S' NOT NULL CHECK (activo IN ('S', 'N')),
    CONSTRAINT fk_prod_categoria FOREIGN KEY (id_categoria)
        REFERENCES CATEGORIAS_PRODUCTO (id_categoria)
);

CREATE TABLE TIENDAS (
    id_tienda        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_tienda    VARCHAR2(30)  NOT NULL UNIQUE,
    nombre_tienda    VARCHAR2(120) NOT NULL UNIQUE,
    canal_venta      VARCHAR2(50)  NOT NULL,
    distrito_zona    VARCHAR2(80)  NOT NULL,
    temperatura_prom NUMBER(5, 2)  DEFAULT 22.00 NOT NULL
);

CREATE TABLE ADMINISTRADORES (
    id_admin         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario          VARCHAR2(60)  NOT NULL UNIQUE,
    nombre_completo  VARCHAR2(150) NOT NULL,
    email            VARCHAR2(150) UNIQUE,
    password_hash    VARCHAR2(255) NOT NULL,
    id_rol           NUMBER        NOT NULL,
    id_estado        NUMBER        NOT NULL,
    face_encoding    CLOB           CHECK (face_encoding IS JSON),
    l2_norm          NUMBER(8, 5),
    fecha_registro   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_admin_rol FOREIGN KEY (id_rol)
        REFERENCES ROLES_SEGURIDAD (id_rol),
    CONSTRAINT fk_admin_estado FOREIGN KEY (id_estado)
        REFERENCES ESTADOS_USUARIO (id_estado)
);

CREATE TABLE ACTIVIDAD_USUARIOS (
    id_actividad     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_admin         NUMBER        NOT NULL,
    fecha_sesion     DATE          NOT NULL,
    tiempo_segundos  NUMBER(6)     DEFAULT 0 NOT NULL CHECK (tiempo_segundos BETWEEN 0 AND 86400),
    primer_ingreso   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ultimo_latido    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_actividad_admin_dia UNIQUE (id_admin, fecha_sesion),
    CONSTRAINT fk_actividad_admin FOREIGN KEY (id_admin)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE CASCADE
);

CREATE TABLE AMPLIACION_AUDITORIA (
    id_auditoria        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_admin_ejecutor   NUMBER        NOT NULL,
    id_admin_objetivo   NUMBER        NULL,
    accion              VARCHAR2(80)  NOT NULL,
    detalle             VARCHAR2(500) NOT NULL,
    fecha_evento        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_aud_ejecutor FOREIGN KEY (id_admin_ejecutor)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE CASCADE,
    CONSTRAINT fk_aud_objetivo FOREIGN KEY (id_admin_objetivo)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE SET NULL
);

CREATE TABLE CONFIGURACION_SEGURIDAD (
    id_config          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_parametro    VARCHAR2(60)  NOT NULL UNIQUE,
    valor_parametro    VARCHAR2(120) NOT NULL,
    id_actualizado_por NUMBER        NULL,
    updated_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_cfg_admin FOREIGN KEY (id_actualizado_por)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE SET NULL
);

CREATE TABLE SOLICITUDES_CAMBIO_CLAVE (
    id_solicitud      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nueva_clave       VARCHAR2(10)  NOT NULL CHECK (REGEXP_LIKE(nueva_clave, '^[0-9]{6}$')),
    id_solicitante    NUMBER        NOT NULL,
    id_aprobador      NUMBER        NULL,
    estado_solicitud  VARCHAR2(20)  DEFAULT 'pendiente' NOT NULL
                      CHECK (estado_solicitud IN ('pendiente', 'aprobada', 'rechazada')),
    created_at        TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    resolved_at       TIMESTAMP WITH TIME ZONE NULL,
    CONSTRAINT chk_doble_superadmin CHECK (id_aprobador IS NULL OR id_solicitante <> id_aprobador),
    CONSTRAINT fk_sol_solicitante FOREIGN KEY (id_solicitante)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE CASCADE,
    CONSTRAINT fk_sol_aprobador FOREIGN KEY (id_aprobador)
        REFERENCES ADMINISTRADORES (id_admin) ON DELETE SET NULL
);

CREATE TABLE TRANSACCIONES_ALICORP (
    id_transaccion    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha_operacion   DATE          NOT NULL,
    id_producto       NUMBER        NOT NULL,
    id_tienda         NUMBER        NOT NULL,
    precio_unitario   NUMBER(10, 2) NOT NULL CHECK (precio_unitario > 0),
    stock_actual      NUMBER(8)     NOT NULL CHECK (stock_actual >= 0),
    temperatura_zona  NUMBER(5, 2)  NOT NULL,
    cantidad_vendida  NUMBER(8)     NOT NULL CHECK (cantidad_vendida >= 0),
    ventas_totales    NUMBER(12, 2) NOT NULL CHECK (ventas_totales >= 0),
    CONSTRAINT fk_trx_producto FOREIGN KEY (id_producto)
        REFERENCES PRODUCTOS (id_producto),
    CONSTRAINT fk_trx_tienda FOREIGN KEY (id_tienda)
        REFERENCES TIENDAS (id_tienda)
);
